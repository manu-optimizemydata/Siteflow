function milestone(
  id: string,
  projectId: string,
  title: string,
  plannedStart: string,
  plannedEnd: string,
  status: Milestone["status"],
  progress: number,
  ownerId: string,
  notes: string,
  dependsOnId?: string,
): Milestone {
  return {
    id,
    companyId,
    projectId,
    title,
    plannedStart,
    plannedEnd,
    actualStart: status === "upcoming" ? undefined : plannedStart,
    actualEnd: status === "completed" ? plannedEnd : undefined,
    ownerId,
    status,
    progress,
    dependsOnId,
    weight: 1,
    notes,
  };
}

